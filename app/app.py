"""Local Gradio demo: recipe generation + flavor pairing.

    python app/app.py                 # cached mode: REAL benchmark generations (instant)
    LIVE_MODEL=1 python app/app.py    # live mode: Gemma 3 270M + trained LoRA adapter on CPU

Cached mode serves outputs saved by the benchmark in ``results/generations/`` for the held-out
prompt closest to your ingredients. Live mode loads ONE model (base + adapter, ~2 GB RAM); the
base-model column then shows the cached base output for the closest held-out prompt.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "src"))

import gradio as gr  # noqa: E402

from recipe_gemma.serve.demo import MODEL_LABELS, Demo, default_root  # noqa: E402

ROOT = Path(os.environ.get("RECIPE_GEMMA_ROOT", default_root()))
DEMO = Demo(ROOT)
ADAPTER = Path(os.environ.get("ADAPTER_PATH", ROOT / "checkpoints" / "smoke" / "adapter.lora.h5"))
LIVE = os.environ.get("LIVE_MODEL") == "1" and DEMO.try_load_live(
    os.environ.get("MODEL_PRESET", "hf://unsloth/gemma-3-270m-it"), str(ADAPTER)
)
CUISINES = ["any", "North American", "Southern European", "Latin American", "East Asian",
            "South Asian", "Southeast Asian", "Middle Eastern", "Western European",
            "Eastern European", "Northern European", "African"]  # fmt: skip

BANNER_CACHED = (
    "**Cached mode:** showing *real* outputs generated by the benchmark "
    "(`results/generations/`) for the held-out test prompt closest to your ingredients. "
    "Start with `LIVE_MODEL=1 python app/app.py` to generate live with the trained adapter."
)
BANNER_LIVE = (
    "**Live mode:** the fine-tuned column is generated now with Gemma 3 270M + LoRA on CPU "
    "(~30-60 s); the base column is the cached base output for the closest held-out prompt."
)


def recipe_fn(ingredients: str, cuisine: str, compare: bool) -> tuple[str, str, str]:
    """Recipe tab handler."""
    items = [i.strip() for i in ingredients.split(",") if i.strip()]
    if not items:
        return "Enter a few comma-separated ingredients.", "", ""
    hit = DEMO.closest_cached(items)
    cached_base = ""
    if hit is not None and compare:
        cached_base = DEMO.cached.get("base", {}).get(hit["id"], {}).get("output", "")
    if LIVE:
        return BANNER_LIVE, DEMO.generate_live(items, cuisine, "finetuned"), cached_base
    if hit is None:
        return "No cached generations yet: run the benchmark (`make eval`).", "", ""
    info = (
        f"{BANNER_CACHED}\n\nClosest held-out prompt (ingredient overlap "
        f"{hit['overlap']:.0%}):\n> {hit['user'].splitlines()[0]}"
    )
    ft = DEMO.cached.get("finetuned", {}).get(hit["id"], {}).get("output", "(not available)")
    return info, ft, cached_base


def pairing_fn(ingredient: str) -> tuple[str, list[list], str, str]:
    """Pairing tab handler."""
    note, rows = DEMO.pairings(ingredient)
    cached = DEMO.cached_pairing_outputs(ingredient)
    return note, rows, cached.get("finetuned", ""), cached.get("base", "")


with gr.Blocks(title="Gemma Recipe & Flavor Pairing") as demo:
    gr.Markdown(
        "# Gemma recipe & flavor-pairing demo (local)\n"
        "Gemma 3 270M with a LoRA adapter fine-tuned locally (Keras 3 + JAX) on a recipe corpus. "
        "Pairings are grounded in corpus PMI and the Ahn et al. (2011) flavor network."
    )
    with gr.Tab("Generate a recipe"):
        with gr.Row():
            ing = gr.Textbox(label="Ingredients (comma-separated)", value="chicken, garlic, lemon")
            cui = gr.Dropdown(CUISINES, value="any", label="Cuisine")
        cmp = gr.Checkbox(value=True, label="Side-by-side: base vs fine-tuned")
        go = gr.Button("Generate", variant="primary")
        info = gr.Markdown()
        with gr.Row():
            out_ft = gr.Textbox(label=MODEL_LABELS["finetuned"], lines=18)
            out_base = gr.Textbox(label=MODEL_LABELS["base"], lines=18)
        go.click(recipe_fn, [ing, cui, cmp], [info, out_ft, out_base])
    with gr.Tab("Find pairings"):
        anchor = gr.Textbox(label="Ingredient", value="tomato")
        find = gr.Button("Find pairings", variant="primary")
        pnote = gr.Markdown()
        table = gr.Dataframe(
            headers=["pairs with", "co-occurring recipes", "NPMI", "shared flavor compounds"],
            interactive=False,
        )
        gr.Markdown("Model answers (cached) when the ingredient is a held-out benchmark anchor:")
        with gr.Row():
            p_ft = gr.Textbox(label=MODEL_LABELS["finetuned"], lines=8)
            p_base = gr.Textbox(label=MODEL_LABELS["base"], lines=8)
        find.click(pairing_fn, [anchor], [pnote, table, p_ft, p_base])
    if not LIVE:  # show an example immediately (cached mode is instant)
        demo.load(recipe_fn, [ing, cui, cmp], [info, out_ft, out_base])

if __name__ == "__main__":
    demo.launch(server_name="127.0.0.1", server_port=int(os.environ.get("PORT", 7860)))
